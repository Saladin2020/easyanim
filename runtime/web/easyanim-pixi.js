// Easy Anim runner for PixiJS v8. Plays an `easyanim/1` cutscene exported by `easyanim export --preset pixi`.
//
//   import { loadCutscene } from "./easyanim-pixi.js";
//   const cs = await loadCutscene(PIXI, "cutscenes/village_morning_delivery.json");
//   app.stage.addChild(cs.view);  cs.play();
//   app.ticker.add((tk) => cs.update(tk.deltaMS / 1000));
//   cs.on("finished", () => …);
//
// Options: { fx, music, sfx, autoAdvance, font }
//   fx    - an Easy FX Pixi loader (loadFx from easyfx-pixi.js): fx.create(id) is used for spawns (else placeholder dots)
//   music - an Easy Music web player (loadMusic from easymusic-web.js): play(id, {fade}) / stop({fade})
//   sfx   - function (id) => void for Easy SFX one-shots
// Events: started, finished, line(line), sfx(id), music(id, fade), music_stop(fade), fx(id, x, y), wait.
// Generated by Easy Anim (MIT).
import { evaluate, safeCount, FRAME, SIDE_ROWS, columnOf } from "./easyanim-core.js";

const UI = { gold: 0xf4ae3d, teak: 0x21160e, cream: 0xf7ebd3, ink: 0x140e0a };

export async function loadCutscene(PIXI, url, opts = {}) {
  const base = new URL(url, document.baseURI);
  const cs = await (await fetch(base)).json();
  if (cs.format !== "easyanim/1") throw new Error(`easyanim: ${url} is not an easyanim/1 cutscene`);
  const rel = (p) => new URL(p, base).href;
  const W = cs.stage.width;
  const H = cs.stage.height;
  const listeners = {};
  const emit = (name, ...args) => (listeners[name] || []).forEach((fn) => fn(...args));

  const view = new PIXI.Container();
  const mask = new PIXI.Graphics().rect(0, 0, W, H).fill(0xffffff);
  view.addChild(mask);
  view.mask = mask;
  const world = new PIXI.Container();
  view.addChild(world);

  const bgTex = await PIXI.Assets.load(rel(cs.assets.backdrop));
  bgTex.source.scaleMode = "nearest";
  world.addChild(new PIXI.Sprite(bgTex));
  const actorLayer = new PIXI.Container();
  actorLayer.sortableChildren = true;
  world.addChild(actorLayer);

  const frames = {};
  for (const [sprite, file] of Object.entries(cs.assets.sprites)) {
    const tex = await PIXI.Assets.load(rel(file));
    tex.source.scaleMode = "nearest";
    frames[sprite] = SIDE_ROWS.map((_, r) => Array.from({ length: 30 }, (_, c) => new PIXI.Texture({ source: tex.source, frame: new PIXI.Rectangle(c * FRAME, r * FRAME, FRAME, FRAME) })));
  }
  const actors = {};
  for (const a of cs.actors) {
    const s = new PIXI.Sprite(frames[a.sprite][0][0]);
    s.anchor.set(0.5, 47 / 48);
    actorLayer.addChild(s);
    actors[a.id] = s;
  }
  const fxLayer = new PIXI.Container();
  world.addChild(fxLayer);
  const dots = new PIXI.Graphics();
  fxLayer.addChild(dots);
  const live = new Map();

  const ui = new PIXI.Container();
  view.addChild(ui);
  const box = new PIXI.Container();
  const panel = new PIXI.Graphics().rect(7, 5, W - 14, 46).fill(UI.ink).rect(8, 6, W - 16, 44).fill(UI.gold).rect(9, 7, W - 18, 42).fill(UI.teak);
  const font = opts.font || "Kanit, sans-serif";
  const nameText = new PIXI.Text({ text: "", style: { fontFamily: font, fontSize: 9, fill: UI.gold } });
  nameText.position.set(14, 8);
  const bodyText = new PIXI.Text({ text: "", style: { fontFamily: font, fontSize: 9, fill: UI.cream, wordWrap: true, breakWords: true, wordWrapWidth: W - 30, lineHeight: 11 } });
  bodyText.position.set(14, 19);
  box.addChild(panel, nameText, bodyText);
  box.visible = false;
  ui.addChild(box);
  const fade = new PIXI.Graphics();
  ui.addChild(fade);

  let time = 0;
  let cursor = 0;
  let playing = false;
  let waiting = false;

  function apply(s) {
    for (const a of s.actors) {
      const spr = actors[a.id];
      const def = cs.actors.find((x) => x.id === a.id);
      spr.visible = a.visible;
      spr.texture = frames[def.sprite][Math.max(0, SIDE_ROWS.indexOf(a.face))][columnOf(a.frame)];
      spr.position.set(Math.round(a.x), Math.round(a.y));
      spr.zIndex = a.y;
    }
    const c = s.camera;
    world.scale.set(c.zoom);
    world.position.set(Math.round(W / 2 - (c.x + c.sx) * c.zoom), Math.round(H / 2 - (c.y + c.sy) * c.zoom));
    // fx: real Easy FX sprites when a loader is given, else small dots
    dots.clear();
    const alive = new Set(s.fx.map((f) => f.i));
    for (const [i, obj] of live) if (!alive.has(i)) (obj.destroy(), live.delete(i));
    for (const f of s.fx) {
      if (opts.fx && opts.fx.ids && opts.fx.ids.includes(f.fx)) {
        if (!live.has(f.i)) {
          const o = opts.fx.create(f.fx);
          o.position.set(f.x, f.y);
          fxLayer.addChild(o);
          o.play && o.play();
          live.set(f.i, o);
        }
      } else {
        for (let k = 0; k < 8; k++) {
          const ang = k * 0.785 + f.i;
          const r = 4 + ((f.age * 18) % 14);
          dots.rect(Math.round(f.x + Math.cos(ang) * r), Math.round(f.y + Math.sin(ang) * r * 0.6 - f.age * 6), 1, 1).fill({ color: 0xffd86a, alpha: Math.max(0, 1 - f.age / Math.max(0.1, f.dur)) });
        }
      }
    }
    fade.clear();
    if (s.fade.a > 0) fade.rect(0, 0, W, H).fill({ color: s.fade.color, alpha: Math.min(1, s.fade.a) });
    box.visible = !!s.line;
    if (s.line) {
      nameText.text = s.line.name;
      bodyText.text = s.line.text ? s.line.text.slice(0, s.line.shown) : `[Easy Dialogue: ${s.line.ref}]`;
    }
    api.state = s;
  }

  function fire(ev) {
    if (ev.op === "sfx") {
      emit("sfx", ev.sfx);
      opts.sfx && opts.sfx(ev.sfx);
    } else if (ev.op === "music") {
      emit("music", ev.music, ev.fade);
      opts.music && opts.music.play(ev.music, { fade: ev.fade });
    } else if (ev.op === "music_stop") {
      emit("music_stop", ev.fade);
      opts.music && opts.music.stop({ fade: ev.fade });
    } else if (ev.op === "spawn") {
      const f = evaluate(cs, ev.t).fx.find((x) => x.i === ev.i);
      if (f) emit("fx", ev.fx, f.x, f.y);
    } else if (ev.op === "line") {
      const l = evaluate(cs, ev.t).line;
      if (l) emit("line", l);
    }
  }

  const api = {
    view,
    data: cs,
    duration: cs.duration,
    state: null,
    get time() {
      return time;
    },
    get waiting() {
      return waiting;
    },
    get playing() {
      return playing;
    },
    on(name, fn) {
      (listeners[name] = listeners[name] || []).push(fn);
      return api;
    },
    play() {
      playing = true;
      emit("started");
    },
    pause() {
      playing = false;
    },
    advance() {
      waiting = false;
    },
    seek(t) {
      time = Math.max(0, Math.min(cs.duration, t));
      waiting = false;
      cursor = 0;
      while (cursor < cs.events.length && (cs.events[cursor].t < time || (time > 0 && cs.events[cursor].t <= time))) cursor++;
      apply(evaluate(cs, time));
    },
    update(dt) {
      if (!playing || waiting) return;
      let t1 = Math.min(cs.duration, time + dt);
      while (cursor < cs.events.length && cs.events[cursor].t <= t1) {
        const ev = cs.events[cursor++];
        fire(ev);
        if (ev.op === "wait_input" && !opts.autoAdvance) {
          t1 = ev.t;
          waiting = true;
          emit("wait");
          break;
        }
      }
      time = t1;
      apply(evaluate(cs, time));
      if (time >= cs.duration && !waiting && cursor >= cs.events.length) {
        playing = false;
        emit("finished");
      }
    },
    safeCount,
  };
  api.seek(0);
  return api;
}
